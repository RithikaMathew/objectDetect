// Run with NODE_PATH pointing to a Playwright installation, isolated API on :8001,
// and the Vite app on :5173. Only the synthetic job is edited/deleted.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
  const seedFs=require('node:fs/promises'),{execFileSync}=require('node:child_process');
  const seedDir='/tmp/cyclescope-browser-data/123456abcd';
  await seedFs.mkdir(seedDir,{recursive:true});
  await seedFs.writeFile(seedDir+'/state.json',JSON.stringify({id:'123456abcd',name:'Synthetic browser verification',status:'ready',progress:1,meta:{fps:30,frames:120,width:640,height:360,pipeline:'xclip_overlay_v19_colonial.py'},tracks:[],calibration:null,decisions:{},analysis:{}}));
  execFileSync('ffmpeg',['-v','error','-y','-f','lavfi','-i','color=c=gray:s=640x360:r=30:d=4','-c:v','libx264','-pix_fmt','yuv420p',seedDir+'/video.mp4']);
  const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/api/**',async route=>{
    const response=await route.fetch({url:route.request().url().replace(/https?:\/\/[^/]+/,'http://127.0.0.1:8001')});
    await route.fulfill({response});
  });
  try {
    await page.goto('http://localhost:5173');
    await page.getByRole('heading',{name:'Recording overview'}).waitFor();
    await page.locator('.dashboard-table tbody tr').first().waitFor();
    const allRows=await page.locator('.dashboard-table tbody tr').count();
    await page.getByLabel('Only locations with bicycle counts').check();
    assert.ok(await page.locator('.dashboard-table tbody tr').count()<allRows);
    for(const cell of await page.locator('.dashboard-table tbody tr td:nth-child(6)').allTextContents())assert.ok(!cell.startsWith('—'));
    await page.getByLabel('Only locations with bicycle counts').uncheck();
    await page.getByLabel('Year',{exact:true}).selectOption('2025');
    assert.match(await page.locator('.dashboard-table').innerText(),/Corrine Dr/);
    await page.getByLabel('Year',{exact:true}).selectOption('all');
    await page.getByText('Associate with a known archive recording (optional)',{exact:true}).click();
    await page.getByLabel('Available recording').selectOption('Annual recordings|10th St|SCU8OG');
    await page.getByLabel('Available date').selectOption('2023-05-02');
    await page.getByLabel('Location',{exact:true}).selectOption('Alafaya East');
    await page.getByText('Available study bicycle counts',{exact:true}).waitFor();
    assert.match(await page.locator('.stats').innerText(),/245/);
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:'/tmp/cyclescope-dashboard-redesign.png',fullPage:true});
    await page.getByRole('link',{name:'Synthetic browser verification'}).click();
    await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
    await page.getByRole('button',{name:'Add missing object',exact:true}).click();
    await page.getByLabel('New object class').selectOption('car');
    let box=await page.locator('canvas').boundingBox();
    const draw=async(dx=0)=>{await page.mouse.move(box.x+50+dx,box.y+50);await page.mouse.down();await page.mouse.move(box.x+150+dx,box.y+150);await page.mouse.up();};
    await draw();
    await page.getByRole('button',{name:/#1 car/}).waitFor();
    await page.getByRole('button',{name:/#1 car/}).click();
    await page.getByText(/^Edit this object/).click();
    await page.getByLabel('Reviewed speed mph').fill('12');
    await page.getByLabel('Speed measurement reason').fill('Synthetic browser review');
    await page.getByRole('button',{name:'Save reviewed speed'}).click();
    await page.getByRole('button',{name:/#1 car/}).filter({hasText:/12 mph.*reviewed/}).waitFor();
    await page.getByLabel('New object class').selectOption('bus');
    await draw(170);
    await page.getByRole('button',{name:/#2 bus/}).click();
    await page.getByRole('button',{name:/#1 car/}).filter({hasText:/12 mph.*reviewed/}).waitFor();
    await page.reload();
    await page.getByRole('button',{name:/#1 car/}).click();
    await page.getByText(/^Edit this object/).click();
    await page.getByLabel('Reviewed speed mph').waitFor();
    assert.equal(await page.getByLabel('Reviewed speed mph').inputValue(),'12');
    await page.getByRole('button',{name:'Restore calculated speed'}).click();
    await page.getByRole('button',{name:/#1 car/}).filter({hasText:'Not measured'}).waitFor();
    await page.getByRole('button',{name:/#2 bus/}).waitFor();
    // The selected car must remain a car; drawing must create the newly chosen class.
    await page.getByRole('button',{name:/#1 car/}).waitFor();
    await page.getByRole('button',{name:/Calibrate \(needed\)/}).click();
    await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2 && document.querySelector('canvas')?.width===document.querySelector('video')?.clientWidth);
    box=await page.locator('canvas').boundingBox();
    for(const [x,y] of [[20,20],[300,20],[300,280],[20,280],[160,150]])await page.mouse.click(box.x+x,box.y+y);
    for(let i=0;i<5;i++){
      await page.getByLabel(`Point ${i+1} X metres`,{exact:true}).fill(String([0,28,28,0,14][i]));
      await page.getByLabel(`Point ${i+1} Y metres`,{exact:true}).fill(String([0,0,26,26,13][i]));
    }
    await page.getByRole('button',{name:'Regions',exact:true}).click();
    await page.getByLabel('Region type').selectOption('sidewalk');
    await page.getByLabel('Region name').fill('sidewalk');
    for(const [x,y] of [[30,30],[140,30],[140,260],[100,280],[30,260]])await page.mouse.click(box.x+x,box.y+y);
    await page.getByRole('button',{name:'Finish polygon (5 points)'}).click();
    await page.getByLabel('Region type').selectOption('bike lane');
    for(const [x,y] of [[160,30],[280,30],[280,260],[160,260]])await page.mouse.click(box.x+x,box.y+y);
    await page.getByRole('button',{name:'Finish polygon (4 points)'}).click();
    await page.getByLabel('Measurement source').fill('Synthetic browser test only');
    await page.getByRole('button',{name:'Save and recompute'}).click();
    await page.getByRole('button',{name:'Calibrate',exact:true}).click();
    await page.getByText('5 landmarks. Click the video to add another.').waitFor();
    await page.getByText('sidewalk · 5 vertices').waitFor();
    await page.getByText('bike lane · 4 vertices').waitFor();
    await page.getByText(/X 20\.0/).first().waitFor();
    await page.screenshot({path:'/tmp/cyclescope-landmarks-regions.png',fullPage:true});
    const fs=require('node:fs/promises'), fixture='/tmp/cyclescope-browser-data/123456abcd/state.json';
    const state=JSON.parse(await fs.readFile(fixture,'utf8'));
    assert.notEqual(state.calibration.regions[0].color,state.calibration.regions[1].color);
    for(let id=3;id<=85;id++)state.tracks.push({...state.tracks[0],id});
    await fs.writeFile(fixture,JSON.stringify(state));
    await page.getByRole('button',{name:'Review',exact:true}).click();
    await page.reload();
    await page.getByRole('button',{name:/#1 car/}).click();
    const before=await page.getByRole('button',{name:'Go to start',exact:true}).boundingBox();
    await page.locator('.review-panel>.list').evaluate(el=>{el.scrollTop=el.scrollHeight;});
    const after=await page.getByRole('button',{name:'Go to start',exact:true}).boundingBox();
    assert.equal(before.y,after.y);
    await page.getByRole('button',{name:'? Ask CycleScope'}).click();
    await page.getByRole('button',{name:'What do Ground X and Ground Y mean?'}).click();
    await page.getByText('They are real distances along the ground', {exact:false}).count();
    await page.getByRole('link',{name:'CycleScope workflow ↗'}).waitFor();
    await page.getByRole('button',{name:'× Close guide'}).click();
    await page.getByRole('button',{name:'Summary',exact:true}).click();
    await page.getByRole('link',{name:'Download CSV'}).waitFor();
    await page.getByRole('button',{name:/Interactions/}).click();
    await page.getByRole('heading',{name:'Interaction controls'}).waitFor();
    await page.screenshot({path:'/tmp/cyclescope-calibration.png',fullPage:true});
    await page.getByRole('link',{name:'CycleScope',exact:true}).click();
    await page.getByRole('button',{name:'Delete',exact:true}).click();
    await page.getByRole('button',{name:'Delete video and results',exact:true}).click();
    await page.getByText('No uploaded videos yet.').waitFor();
    const batchFile='/tmp/cyclescope-batch.mp4';
    require('node:child_process').execFileSync('ffmpeg',['-v','error','-y','-f','lavfi','-i','color=c=gray:s=640x360:r=30:d=4','-c:v','libx264','-pix_fmt','yuv420p',batchFile]);
    const data=await fs.readFile(batchFile);
    await page.getByLabel('Choose local videos').setInputFiles([{name:'first.mp4',mimeType:'video/mp4',buffer:data},{name:'second.mp4',mimeType:'video/mp4',buffer:data}]);
    await page.getByRole('button',{name:'Process 2 selected videos'}).waitFor({state:'visible'});
    await page.locator('.upload-card').first().getByRole('button',{name:'First 10 minutes'}).click();
    await page.locator('.upload-card').last().getByRole('button',{name:'Last 15 minutes'}).click();
    await page.getByLabel('Clip end first.mp4').focus();
    for(let i=0;i<15;i++)await page.keyboard.press('ArrowLeft');
    await page.getByLabel('Clip start first.mp4').focus();
    for(let i=0;i<5;i++)await page.keyboard.press('ArrowRight');
    await page.screenshot({path:'/tmp/cyclescope-batch-selection.png',fullPage:true});
    await page.getByRole('button',{name:'Process 2 selected videos'}).click();
    await page.getByRole('link',{name:'Open processing / review'}).nth(1).waitFor();
    await page.waitForFunction(()=>Array.from(document.querySelectorAll('.jobs .chip')).filter(x=>x.textContent==='ready').length===2);
    const response=await page.request.get('http://127.0.0.1:8001/api/jobs');
    const jobs=await response.json();assert.equal(jobs.length,2);
    const first=jobs.find(j=>j.name==='first.mp4');
    const prepared=await (await page.request.get(`http://127.0.0.1:8001/api/jobs/${first.id}`)).json();
    assert.ok(Math.abs(prepared.clip_start_s-.5)<.01);assert.ok(Math.abs(prepared.clip_end_s-2.5)<.01);
    assert.ok(Math.abs(prepared.meta.selected_duration_s-2)<.01);
    for(const job of jobs)await page.request.delete(`http://127.0.0.1:8001/api/jobs/${job.id}`);

    assert.deepEqual(errors,[]);
    await page.screenshot({path:'/tmp/cyclescope-dashboard.png',fullPage:true});
    console.log('PASS: bicycle-count filter; reviewed speed save/restore; batch uploads with selected clip extraction; all-year dashboard and date selectors; chosen-class drawing; five landmarks; distinct sidewalk/bike-lane colors persisted; object actions fixed while 85 rows scroll; interaction/summary controls; deletion; no browser JS errors.');
  }catch(e){await page.screenshot({path:'/tmp/cyclescope-browser-failure.png',fullPage:true});console.log((await page.locator('body').innerText()).slice(-5000));throw e;}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
